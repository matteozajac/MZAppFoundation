#!/usr/bin/env python3
"""Stamp safe source identities and resolved versions. No environment or remote URLs are exported."""
import argparse
from datetime import datetime, timezone
import json
import os
from pathlib import Path
import plistlib
import re
import subprocess


def git_identity(root):
    if root is None:
        return None, None
    def run(*arguments):
        result = subprocess.run(['git', '-C', str(root), *arguments], text=True, capture_output=True)
        return result.stdout.strip() if result.returncode == 0 else None
    revision = run('rev-parse', 'HEAD')
    if not revision or not re.fullmatch(r'[0-9a-f]{40,64}', revision):
        return None, None
    status = run('status', '--porcelain', '--untracked-files=normal')
    return revision, bool(status) if status is not None else None


def find_resolved(root):
    if root is None:
        return None
    candidates = [root / 'Package.resolved']
    candidates += sorted(root.glob('*.xcodeproj/project.xcworkspace/xcshareddata/swiftpm/Package.resolved'))
    candidates += sorted(root.glob('*.xcworkspace/xcshareddata/swiftpm/Package.resolved'))
    return next((path for path in candidates if path.is_file()), None)


def resolved_pins(path):
    if path is None or not path.is_file():
        return {}
    payload = json.loads(path.read_text())
    pins = payload.get('pins', payload.get('object', {}).get('pins', []))
    safe = {}
    for pin in pins:
        identity = pin.get('identity', pin.get('package', '')).lower()
        if not re.fullmatch(r'[a-z0-9._-]+', identity):
            continue
        state = pin.get('state', {})
        version = state.get('version')
        revision = state.get('revision')
        if isinstance(version, str) and re.fullmatch(r'[A-Za-z0-9.+_-]+', version):
            safe[identity] = {'version': version}
        elif isinstance(revision, str) and re.fullmatch(r'[0-9a-f]{40,64}', revision):
            safe[identity] = {'version': 'revision:' + revision}
        else:
            continue
        if isinstance(revision, str) and re.fullmatch(r'[0-9a-f]{40,64}', revision):
            safe[identity]['revision'] = revision
    return safe


def foundation_version(root, fallback=None):
    path = root / 'VERSION' if root else None
    value = path.read_text().strip() if path and path.is_file() else fallback
    if value is None:
        return 'Unknown'
    if not re.fullmatch(r'\d+\.\d+\.\d+(?:[-+][A-Za-z0-9.-]+)?', value):
        raise ValueError('Invalid foundation version')
    return value


def generate(app_root, foundation_root=None, resolved=None, version=None, channel=None, timestamp=None):
    app_revision, app_modified = git_identity(app_root)
    library_revision, library_modified = git_identity(foundation_root)
    app_pins = resolved_pins(resolved or find_resolved(app_root))
    library_pins = resolved_pins(find_resolved(foundation_root))
    pins = app_pins or library_pins
    foundation_pin = app_pins.get('mzappfoundation', {})
    if foundation_root is None:
        library_revision = foundation_pin.get('revision')
    if channel is not None and not re.fullmatch(r'[A-Za-z0-9 ._+-]{1,80}', channel):
        raise ValueError('Invalid build channel')
    output = {
        'foundationVersion': foundation_version(foundation_root, foundation_pin.get('version') or version),
        'resolvedPackageVersions': {name: data['version'] for name, data in sorted(pins.items())},
        'provenance': 'App Package.resolved and build source identities' if app_pins else
                      'Library Package.resolved snapshot and build source identities' if library_pins else
                      'Build source identities; no Package.resolved was available'
    }
    for key, value in [('appRevision', app_revision), ('foundationRevision', library_revision),
                       ('appWorkingTreeModified', app_modified), ('foundationWorkingTreeModified', library_modified),
                       ('buildChannel', channel)]:
        if value is not None:
            output[key] = value
    if timestamp is not None:
        output['buildDate'] = datetime.fromtimestamp(int(timestamp), timezone.utc).replace(tzinfo=None)
    return output


def swift_source(root):
    versions = {name: data['version'] for name, data in resolved_pins(find_resolved(root)).items()}
    rows = ',\n'.join(f'        {json.dumps(name)}: {json.dumps(version)}' for name, version in sorted(versions.items()))
    return ('// Generated by scripts/generate_build_metadata.py from VERSION and Package.resolved.\n'
            '// These pins describe the library checkout. Runtime adapters report their linked SDK versions separately.\n'
            'public enum FoundationVersion {\n'
            f'    public static let current = {json.dumps(foundation_version(root))}\n'
            '    public static let resolvedPackageVersions: [String: String] = [\n' + rows + '\n    ]\n}\n')


def write_if_changed(path, data):
    if path.is_file() and path.read_bytes() == data:
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(data)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--app-root', type=Path)
    parser.add_argument('--foundation-root', type=Path)
    parser.add_argument('--resolved', type=Path)
    parser.add_argument('--foundation-version')
    parser.add_argument('--channel')
    parser.add_argument('--timestamp', default=os.environ.get('SOURCE_DATE_EPOCH'))
    parser.add_argument('--stamp-build-time', action='store_true')
    parser.add_argument('--output', type=Path)
    parser.add_argument('--foundation-swift-output', type=Path)
    args = parser.parse_args()
    if args.foundation_swift_output:
        if not args.foundation_root:
            parser.error('--foundation-root is required for a generated Swift source')
        write_if_changed(args.foundation_swift_output, swift_source(args.foundation_root).encode())
    if args.output:
        if not args.app_root:
            parser.error('--app-root is required for metadata output')
        timestamp = args.timestamp
        if args.stamp_build_time and timestamp is None:
            timestamp = int(datetime.now(timezone.utc).timestamp())
        metadata = generate(args.app_root, args.foundation_root, args.resolved, args.foundation_version,
                            args.channel, timestamp)
        write_if_changed(args.output, plistlib.dumps(metadata, sort_keys=True))
    if not args.output and not args.foundation_swift_output:
        parser.error('Choose a metadata or Swift output')


if __name__ == '__main__':
    main()
